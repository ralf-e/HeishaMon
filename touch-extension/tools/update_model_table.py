"""Generate the display-only model table from a reviewed upstream Markdown snapshot."""
from pathlib import Path
import argparse,hashlib,json,re
ROOT=Path(__file__).resolve().parents[1]
COMMIT='b3ef43691f21985c851903d69a0f2e8647ed31f8'
def generate(source,commit,check=False):
 data=source.read_bytes();rows=[]
 for line in data.decode('utf8').splitlines():
  cells=[x.strip() for x in line.strip().strip('|').split('|')]
  if len(cells)!=8 or not cells[0].isdigit():continue
  key=cells[1].upper().split()
  if len(key)!=10 or any(not re.fullmatch('[0-9A-F]{2}',x) for x in key):
   raise ValueError('Invalid model signature in row '+cells[0])
  rows.append(dict(id=int(cells[0]),key=' '.join(key),idu=cells[2],odu=cells[3],
                   kit=cells[4],power=cells[5],phase=cells[6],type=cells[7]))
 if not rows:raise ValueError('No model rows found')
 if len({r['id'] for r in rows})!=len(rows):raise ValueError('Duplicate model IDs')
 duplicates={}
 for r in rows:duplicates.setdefault(r['key'],[]).append(r['id'])
 duplicates={k:v for k,v in duplicates.items() if len(v)>1}
 h=['// Generated by tools/update_model_table.py; do not edit.',
    '// Source: https://github.com/heishamon/HeishaMon/blob/'+commit+'/HeatPumpType.md',
    '// Included inside namespace hmx after ModelRecord is declared.',
    'constexpr ModelRecord modelRecords[] = {']
 for r in rows:
  values=','.join(json.dumps(r[k],ensure_ascii=True) for k in ['idu','odu','kit','power','phase','type'])
  h.append('  {{'+','.join('0x'+v for v in r['key'].split())+'},'+values+','+str(r['id'])+'},')
 h+=['};','constexpr unsigned modelCount = sizeof(modelRecords)/sizeof(modelRecords[0]);',
     'constexpr const char modelTableCommit[] = "'+commit+'";','']
 meta=dict(source_url='https://github.com/heishamon/HeishaMon/blob/'+commit+'/HeatPumpType.md',
           upstream_commit=commit,sha256=hashlib.sha256(data).hexdigest(),count=len(rows),
           duplicate_signatures=duplicates,rows=rows)
 outputs={ROOT/'extension/hmx_model_data.h':'\n'.join(h),
          ROOT/'docs/model_catalogue.json':json.dumps(meta,indent=2,ensure_ascii=True)+'\n'}
 for p,s in outputs.items():
  if check:
   if p.read_text(encoding='utf8')!=s:raise ValueError('Generated file differs: '+str(p))
  else:p.write_text(s,encoding='utf8')
 print(str(len(rows))+' model records; '+str(len(duplicates))+' ambiguous signatures; '+('check OK' if check else 'generated'))
if __name__=='__main__':
 p=argparse.ArgumentParser();p.add_argument('--source',type=Path,default=ROOT/'upstream-reference/HeatPumpType.md')
 p.add_argument('--commit');p.add_argument('--check',action='store_true');a=p.parse_args()
 previous=ROOT/'docs/model_catalogue.json'
 commit=a.commit or (json.loads(previous.read_text())['upstream_commit'] if previous.exists() else COMMIT)
 generate(a.source,commit,a.check)
